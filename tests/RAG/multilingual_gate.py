def write_fixtures() -> list[Path]:
    FIXTURES.mkdir(parents=True, exist_ok=True)
    written = []
    for spec in CORPUS.values():
        p = FIXTURES / spec["name"]
        p.write_text(spec["text"], encoding="utf-8")
        written.append(p)
    (FIXTURES / "README.md").write_text(
        "Generated by tests/RAG/multilingual_gate.py (F25d).\n\n"
        "Seven scripts plus one mixed-script document, all saying the same thing about\n"
        "refunds, so a retrieval miss is attributable to the script and not the content.\n"
        "Regenerate by running the gate; do not hand-edit.\n",
        encoding="utf-8",
    )
    return written


def main() -> int:
    from rag import answer, embed, sira

    print("=" * 72)
    print("F25d - multilingual mock corpus and edge cases")
    print("=" * 72)
    files = write_fixtures()
    print(f"wrote {len(files)} fixtures to {FIXTURES}")
    print(f"embedder in use: {embed.backend_name()} dim={embed.active_dim()}")
    print()

    print("--- 1. tokenizer sees the query at all ---")
    for lang, spec in CORPUS.items():
        toks = sira.tokenize(spec["query"])
        check(bool(toks), f"{lang}: query yields >=1 token",
              f"sira.tokenize -> {toks!r} (rag/sira.py:13 is ASCII-only)")

    print()
    print("--- 2. coverage does not claim success it cannot measure ---")
    # Evidence deliberately unrelated: a correct coverage score here is LOW.
    unrelated = [{"heading": "Bicycles", "path": "bikes.md",
                  "text": "everything you need to know about bicycle maintenance"}]
    for lang, spec in CORPUS.items():
        cov = answer._coverage(spec["query"], unrelated)
        # 1.0 against unrelated evidence is the vacuous case: no salient tokens,
        # so the corrective loop never fires and stop_reason becomes evidence_ok.
        check(cov < 0.6, f"{lang}: unrelated evidence scores below the 0.6 floor",
              f"coverage={cov:.2f} - vacuous full coverage, retrieval loop never fires")

    print()
    print("--- 3. embedder distinguishes the corpus from unrelated text ---")
    try:
        base = embed.embed_text(CORPUS["en"]["text"])
        for lang in ("zh", "ja", "ar", "ru"):
            v = embed.embed_text(CORPUS[lang]["text"])
            same = sum(a * b for a, b in zip(base, v))
            # Same meaning, different script: a multilingual embedder should place
            # these near the English original. An English-only model has no reason to.
            check(same > 0.5, f"{lang}: same meaning embeds near the English text",
                  f"cosine={same:.3f} vs en (model={getattr(embed, 'BGE_MODEL_ID', '?')} is English-only)")
    except Exception as exc:
        check(False, "embedder probe ran", f"{type(exc).__name__}: {exc}")

    print()
    print("--- 4. whitespace tokenization on scripts without spaces ---")
    for lang in ("zh", "ja", "th"):
        n = len(CORPUS[lang]["text"].split())
        # The hash backend splits on whitespace; a spaceless script collapses to
        # one token, so an entire document hashes to a single lane.
        check(n >= 5, f"{lang}: text splits into >=5 whitespace tokens",
              f"splits into {n} - under the hash backend this is ~1 vector lane")

    print()
    print("--- 5. mixed-script document keeps its ASCII anchors ---")
    mixed = sira.tokenize(CORPUS["mixed"]["text"])
    check("sku-00397" in mixed, "mixed: SKU code survives tokenization", f"tokens={mixed[:8]}")
    check(any("退款" in t for t in mixed), "mixed: CJK term survives tokenization",
          f"tokens={mixed[:8]} - ASCII anchors survive, CJK is dropped entirely")

    print()
    print("=" * 72)
    total = PASS + len(FAIL)
    print(f"{PASS}/{total} checks passed")
    if FAIL:
        print(f"\n{len(FAIL)} FAILING - this is the multilingual definition of done:")
        for f in FAIL:
            print(f"  - {f}")
        print("\nRoot cause for most: rag/sira.py:13 is ASCII-only. Fixing it re-indexes")
        print("the corpus, so it is gated behind rag/index_fingerprint.py.")
    return 1 if FAIL else 0


if __name__ == "__main__":
    raise SystemExit(main())
