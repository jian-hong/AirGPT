"""Mock multilingual corpus and the edge cases it has to survive (F25d).

Authorized shape: multilingual as an OPT-IN alternative, mock fixtures first, then
work the edge cases. So this generates the corpus and then probes the seams -
tokenizer, coverage, embedder - rather than asserting a feature that is not built.

THIS GATE IS EXPECTED TO FAIL TODAY. That is its job. It is the written-down
definition of done for the multilingual work, and every FAIL below is a real
defect reproduced on a real corpus, not a hypothetical. It is deliberately NOT
wired into CI: a permanently red check trains people to ignore red (R-0002 cuts
both ways - a test nobody believes is worse than no test).

The root cause under most of these is one line, `rag/sira.py:13`:

    _TOKEN_RE = re.compile(r"[A-Za-z0-9_][A-Za-z0-9_\\-./]{1,}")

An ASCII-only character class beneath tokenization, salient terms, coverage and
index phrases. Fixing it changes what gets indexed, so it is gated behind the
index fingerprint (rag/index_fingerprint.py) - a score taken before that change
is not comparable to one taken after.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parents[1]
for _p in (str(REPO), str(ROOT)):
    if _p not in sys.path:
        sys.path.insert(0, _p)

from scripts.stdio_utf8 import ensure_utf8_stdio  # noqa: E402

if not ensure_utf8_stdio():
    print("[warn] stdout is not UTF-8; this gate prints six scripts and will be lossy")

FIXTURES = ROOT / "multilingual"

PASS = 0
FAIL: list[str] = []


def check(ok: bool, label: str, detail: str = "") -> None:
    global PASS
    if ok:
        PASS += 1
        print(f"  PASS  {label}")
    else:
        FAIL.append(label)
        print(f"  FAIL  {label}" + (f"\n          {detail}" if detail else ""))


# One refund-policy document per script, same meaning, so a retrieval miss is
# about the script and not about the content differing.
